1. **A Ectenia dos Fiéis**
2. **O Credo Niceno-Constantinopolitano**
3. **A Anáfora** — a oração eucarística
4. **A Epiclese** — invocação do Espírito Santo
5. **A Comunhão** — recepção do Corpo e Sangue

